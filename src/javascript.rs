/// What JavaScript writes for the built-in function `name`, if anything.
pub fn equivalents(name: &str) -> impl Iterator<Item = &'static str> + '_ {
    EQUIVALENTS.iter().filter(move |(r, _)| *r == name).map(|(_, js)| *js)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Every Rythme name of the table is a built-in function (the new ones
    /// included): the site links each to its page.
    #[test]
    fn every_name_is_a_builtin() {
        for (name, js) in EQUIVALENTS {
            assert!(crate::builtins::lookup(name).is_some(), "{name} (for {js}) is not a built-in function");
        }
    }
}
